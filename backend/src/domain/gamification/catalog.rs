pub fn all_badges() -> Vec<BadgeMeta> {
    BADGE_DEFS
        .iter()
        .map(|&(id, track, title, desc, threshold, xp, icon)| BadgeMeta {
            id: id.to_string(),
            track: track.to_string(),
            title: title.to_string(),
            description: desc.to_string(),
            threshold,
            reward_xp: xp,
            icon: icon.to_string(),
        })
        .collect()
}
